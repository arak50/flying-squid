'use strict'
/**
 * Regenerates lib/armorSets.js from the SkyBlock items endpoint dump.
 *
 *   node tools/build-armor-sets.js /path/to/items.json
 *
 * Only the pieces listed in SETS are kept. Per piece we store the modern item name, the dye colour (leather only) and, for
 * skulls, the texture hash (what the client downloads from textures.minecraft.net), not the 700-character signed blob.
 */
const fs = require('fs')
const path = require('path')

// set key -> item id pattern; `{P}` is replaced by helmet / chestplate / leggings / boots in upper case
const SETS = {
  young_dragon: 'YOUNG_DRAGON_{P}',
  unstable_dragon: 'UNSTABLE_DRAGON_{P}',
  holy_dragon: 'HOLY_DRAGON_{P}',
  superior_dragon: 'SUPERIOR_DRAGON_{P}',
  perfect: 'PERFECT_{P}_1', // tier I; every tier is the same diamond model
  shadow_assassin: 'SHADOW_ASSASSIN_{P}',
  golden: 'GOLD_{P}', // King Midas
  frozen_blaze: 'FROZEN_BLAZE_{P}',
  heavy: 'HEAVY_{P}',
  super_heavy: 'SUPER_HEAVY_{P}',
  zombie_soldier: 'ZOMBIE_SOLDIER_{P}',
  zombie_knight: 'ZOMBIE_KNIGHT_{P}',
  zombie_commander: 'ZOMBIE_COMMANDER_{P}',
  zombie_lord: 'ZOMBIE_LORD_{P}',
  skeleton_grunt: 'SKELETON_GRUNT_{P}',
  skeleton_soldier: 'SKELETON_SOLDIER_{P}',
  skeleton_master: 'SKELETON_MASTER_{P}',
  skeleton_lord: 'SKELETON_LORD_{P}',
  skeletor: 'SKELETOR_{P}',
  bouncy: 'BOUNCY_{P}'
}
// sets that are only a head piece
const SINGLE = { sniper: ['helmet', 'SNIPER_HELMET'] }

const PIECES = ['helmet', 'chestplate', 'leggings', 'boots']
const MATERIAL = { LEATHER: 'leather', GOLD: 'golden', CHAINMAIL: 'chainmail', IRON: 'iron', DIAMOND: 'diamond' }

function textureHash (skin) {
  const json = JSON.parse(Buffer.from(skin.value, 'base64').toString('utf8'))
  const url = json.textures.SKIN.url
  return url.slice(url.lastIndexOf('/') + 1)
}

function convert (item, piece) {
  const m = String(item.material)
  if (m === 'SKULL_ITEM') {
    if (!item.skin) throw new Error(`${item.id}: skull without a skin`)
    return { item: 'player_head', skin: textureHash(item.skin) }
  }
  const [mat, kind] = m.split('_')
  if (!MATERIAL[mat] || kind.toLowerCase() !== piece) throw new Error(`${item.id}: unexpected material ${m}`)
  const out = { item: `${MATERIAL[mat]}_${piece}` }
  if (mat === 'LEATHER' && item.color) { const [r, g, b] = item.color.split(',').map(Number); out.color = (r << 16) | (g << 8) | b }
  return out
}

function main (file) {
  const items = JSON.parse(fs.readFileSync(file, 'utf8')).items
  const byId = new Map(items.map(i => [i.id, i]))
  const get = id => { const i = byId.get(id); if (!i) throw new Error(`missing in items.json: ${id}`); return i }
  const out = {}
  for (const [key, pattern] of Object.entries(SETS)) {
    out[key] = {}
    for (const piece of PIECES) out[key][piece] = { ...convert(get(pattern.replace('{P}', piece.toUpperCase())), piece), id: pattern.replace('{P}', piece.toUpperCase()) }
  }
  for (const [key, [piece, id]] of Object.entries(SINGLE)) out[key] = { [piece]: { ...convert(get(id), piece), id } }

  const body = JSON.stringify(out, null, 2).replace(/"([a-z_]+)":/g, '$1:').replace(/"/g, "'")
  const header = [
    "'use strict'",
    '// GENERATED by tools/build-armor-sets.js from the SkyBlock items endpoint. Do not edit by hand.',
    '// piece = { item: modern item name, color?: leather dye (0xRRGGBB), skin?: skull texture hash, id: SkyBlock item id }',
    'module.exports = '
  ].join('\n')
  fs.writeFileSync(path.join(__dirname, '..', 'lib', 'armorSets.js'), header + body + '\n')
  console.log(`wrote ${Object.keys(out).length} sets`)
}

if (!process.argv[2]) { console.error('usage: node tools/build-armor-sets.js items.json'); process.exit(1) }
main(process.argv[2])
